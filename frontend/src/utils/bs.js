const LAST_YEAR = FIRST_YEAR + MONTH_DAYS.length - 1
const EPOCH = Date.UTC(1918, 3, 13) // 1975-01-01 BS (1 Baisakh 1975) was 13 April 1918 AD
const DAY = 86400000

export const BS_MONTHS = ['Baisakh', 'Jestha', 'Ashadh', 'Shrawan', 'Bhadra', 'Ashwin',
  'Kartik', 'Mangsir', 'Poush', 'Magh', 'Falgun', 'Chaitra']

// Days from the epoch to the start of each BS year, computed once.
const YEAR_START = [0]
for (const months of MONTH_DAYS) YEAR_START.push(YEAR_START.at(-1) + months.reduce((a, b) => a + b, 0))

const pad = (n, w = 2) => String(n).padStart(w, '0')

export function daysInBsMonth(year, month) {
  return MONTH_DAYS[year - FIRST_YEAR]?.[month - 1] ?? 0
}

export function isValidBs(year, month, day) {
  return Number.isInteger(year) && Number.isInteger(month) && Number.isInteger(day) &&
    year >= FIRST_YEAR && year <= LAST_YEAR && month >= 1 && month <= 12 && day >= 1 && day <= daysInBsMonth(year, month)
}

/** BS date → AD "YYYY-MM-DD": days since the epoch = whole years + whole months + days. */
export function bsToAd(year, month, day) {
  if (!isValidBs(year, month, day)) throw new RangeError(`${year}-${pad(month)}-${pad(day)} is not a BS date in ${FIRST_YEAR}–${LAST_YEAR}`)
  let days = YEAR_START[year - FIRST_YEAR]
  for (let m = 1; m < month; m++) days += daysInBsMonth(year, m)
  return new Date(EPOCH + (days + day - 1) * DAY).toISOString().slice(0, 10)
}

/** AD date ("YYYY-MM-DD" or Date) → { year, month, day } in BS, or null outside the table. */
export function adToBs(ad) {
  const t = typeof ad === 'string' ? Date.UTC(+ad.slice(0, 4), +ad.slice(5, 7) - 1, +ad.slice(8, 10))
    : Date.UTC(ad.getFullYear(), ad.getMonth(), ad.getDate())
  let days = Math.round((t - EPOCH) / DAY)
  if (Number.isNaN(days) || days < 0 || days >= YEAR_START.at(-1)) return null
  let lo = 0, hi = MONTH_DAYS.length - 1 // binary search for the year that contains this day
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1
    if (YEAR_START[mid] <= days) lo = mid
    else hi = mid - 1
  }
  days -= YEAR_START[lo]
  let month = 0
  while (days >= MONTH_DAYS[lo][month]) days -= MONTH_DAYS[lo][month++]
  return { year: FIRST_YEAR + lo, month: month + 1, day: days + 1 }
}

/** "2026-11-13" → "2083-07-27"; empty string when there is no date or it is outside the table. */
export function formatBs(ad) {
  if (!ad) return ''
  const b = adToBs(String(ad).slice(0, 10))
  return b ? `${b.year}-${pad(b.month)}-${pad(b.day)}` : ''
}

/** "2083-07-27" or "2083/7/27" → { year, month, day }, or null if it is not a valid BS date. */
export function parseBs(text) {
  const m = String(text).trim().match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})$/)
  if (!m) return null
  const [year, month, day] = [Number(m[1]), Number(m[2]), Number(m[3])]
  return isValidBs(year, month, day) ? { year, month, day } : null
}

/** Today's date in BS. */
export const todayBs = () => formatBs(new Date().toLocaleDateString('en-CA'))
